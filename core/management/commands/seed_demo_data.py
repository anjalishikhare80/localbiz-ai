def season_factor(tag, d):
    m = d.month
    if tag == "school":  # school reopening (June-July) and exam period (Feb-Mar)
        return {6: 2.2, 7: 1.8, 8: 1.1, 2: 1.2, 3: 1.4}.get(m, 0.8)
    if tag == "festival":  # Diwali window (Oct-Nov)
        return 3.0 if m in (10, 11) else 0.5
    if tag == "december":
        return 4.0 if m in (12, 1) else 0.2
    return 1.0


class Command(BaseCommand):
    help = "Create a synthetic demo business with ~8 months of sales and train the ML models."

    def add_arguments(self, parser):
        parser.add_argument("--days", type=int, default=240, help="Days of history to simulate (default 240).")
        parser.add_argument("--reset", action="store_true", help="Delete an existing demo business first.")
        parser.add_argument("--seed", type=int, default=42)
        parser.add_argument("--no-train", action="store_true", help="Skip ML training at the end.")

    def handle(self, *args, **opts):
        rng, nprng = random.Random(opts["seed"]), np.random.default_rng(opts["seed"])
        existing = Business.objects.filter(name=DEMO_NAME).first()
        if existing and not opts["reset"]:
            raise CommandError("Demo business already exists. Use --reset to rebuild it.")
        if existing:
            existing.delete()
            self.stdout.write("Old demo business removed.")

        owner = self._user("demo_owner", "owner@demo.localbiz", "Demo@12345")
        manager = self._user("demo_manager", "manager@demo.localbiz", "Demo@12345")
        employee = self._user("demo_employee", "employee@demo.localbiz", "Demo@12345")
        business = create_business_with_owner(user=owner, name=DEMO_NAME, business_type="STATIONERY")
        business.tax_rate = Decimal("5.00")
        business.address = "Shop 4, Market Road, Pandharpur (demo address)"
        business.phone = "0000000000"
        business.save()
        BusinessMember.objects.create(user=manager, business=business, role="MANAGER")
        BusinessMember.objects.create(user=employee, business=business, role="EMPLOYEE")

        cats = {n: Category.objects.create(business=business, name=n) for n in sorted({p[2] for p in PRODUCTS})}
